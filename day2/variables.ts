//  var vs let vs const

/*
    1. Scope
    2. Declaration/value assignment
    3.Re-declaration
    4.Re-initialization/ Re-assignment
    5.Hoisting
 */

/* // 1. Scope
      var - function scope
      let and const - block scope */

/* //  2. Declaration/value assignment
    var and let - Not Mandatory
    const - Mandatory */

/* //  3. Re-declaration
    var - Allowed
    let and const - Not Allowed */

/* //  4. Re-initialization/ Re-assignment
    var and let - Allowed
    const - Not Allowed */

/* // 5. Hoisting
   var - Avoid
   let -   Changing values
   const -   Constant values  */